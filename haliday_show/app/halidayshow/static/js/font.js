// A few more that festive messages want.
const EXTRA = {
  "£": [0x48, 0x7e, 0x49, 0x41, 0x42],
  "♥": [0x0c, 0x1e, 0x3c, 0x1e, 0x0c],
  "★": [0x24, 0x1c, 0x1f, 0x1c, 0x24],
  "°": [0x00, 0x06, 0x09, 0x09, 0x06],
};

// A character's 5 columns. Accented letters lose their accents; anything else becomes "?".
export function glyph(ch) {
  if (EXTRA[ch]) return EXTRA[ch];
  let c = ch.charCodeAt(0);
  if (!(c >= 32 && c < 127)) {
    const bare = ch.normalize("NFD").replace(/[̀-ͯ]/g, "");
    c = bare.length === 1 && bare.charCodeAt(0) >= 32 && bare.charCodeAt(0) < 127 ? bare.charCodeAt(0) : 63;
  }
  const k = (c - 32) * GLYPH_W;
  return ASCII.slice(k, k + GLYPH_W);
}

// A message as columns of dots, each letter followed by a blank column. Kept per message, as effects
// ask for the same one every frame.
const cache = new Map();
export function textColumns(text) {
  const key = String(text ?? "");
  let cols = cache.get(key);
  if (!cols) {
    cols = [...key].flatMap((ch) => [...glyph(ch), 0]);
    if (cache.size < 256) cache.set(key, cols);
  }
  return cols;
}
